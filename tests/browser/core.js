async (page) => {
  const fixture = await page.request.get('http://127.0.0.1:8000/api/health');
  if (fixture.headers()['x-ai-tutor-test-fixture'] !== 'temporary-data;mock-deepseek') throw new Error('Use tests/browser_server.py: refusing to test against production data');
  const checks = [];
  const ensure = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.goto('http://127.0.0.1:8000/');
  await page.locator('.monaco-editor').waitFor();
  const history = async () => (await page.request.get('http://127.0.0.1:8000/api/history')).json();
  const select = async (id) => {
    await page.getByRole('button', { name: '题库', exact: true }).click();
    await page.getByRole('textbox', { name: '搜索题目' }).fill(String(id));
    await page.getByText('1 道匹配题目', { exact: true }).waitFor();
    await page.locator('.problem-row').first().click();
    await page.locator('.monaco-editor').waitFor();
  };
  const setCode = async (id, code) => {
    await page.locator('.monaco-editor').click({ position: { x: 120, y: 65 } });
    await page.keyboard.press('Control+A');
    await page.evaluate(text => {
      const data = new DataTransfer(); data.setData('text/plain', text);
      document.activeElement.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }));
    }, code);
    await page.waitForFunction(([pid, expected]) => localStorage.getItem(`ai-tutor:draft:v1:${pid}`) === expected, [id, code]);
  };
  await select(198);
  const first = '# 浏览器验收草稿：不会执行代码\nclass Solution:\n    def rob(self, nums):\n        # 先检查边界，再推演相邻选择\n        total = 0\n        for i in range(len(nums)):\n            if nums[i] > nums[i + 1]:\n                total += nums[i]\n        return total\n';
  await setCode(198, first);
  await page.reload();
  await page.locator('.monaco-editor').waitFor();
  await page.waitForFunction(() => document.querySelector('.monaco-editor')?.innerText.includes('total'));
  ensure(await page.locator('.monaco-editor').innerText().then(text => text.includes('total')), 'refresh restores Monaco draft');
  await select(20);
  await setCode(20, '# independent second draft\npass\n');
  await select(198);
  await page.waitForFunction(() => document.querySelector('.monaco-editor')?.innerText.includes('total'));
  ensure(await page.locator('.monaco-editor').innerText().then(text => text.includes('total')), 'switching problems restores independent draft');
  await page.getByRole('button', { name: '学习路线', exact: true }).click();
  await page.locator('.heatmap-day').first().waitFor();
  ensure(await page.locator('.heatmap-grid .heatmap-day').count() === 365, 'real Python heatmap contains 365 days');
  ensure(await page.locator('.route-stage').count() === 8, 'eight Python learning stages remain available');
  await page.getByRole('button', { name: '工作台', exact: true }).click();
  await page.locator('.monaco-editor').waitFor();
  await page.waitForFunction(() => document.querySelector('.monaco-editor')?.innerText.includes('total'));
  ensure(await page.locator('.monaco-editor').innerText().then(text => text.includes('total')), 'navigation preserves code buffer');
  const before = await history();
  await page.getByRole('button', { name: 'AI 诊断', exact: true }).click();
  await page.locator('.hint-card').first().waitFor();
  ensure(await page.locator('.hint-card').count() === 1, 'AI initially reveals exactly Hint 1');
  await page.getByRole('button', { name: /查看下一条提示/ }).click();
  await page.waitForFunction(() => document.querySelectorAll('.hint-card').length === 2);
  await page.getByRole('button', { name: /查看下一条提示/ }).click();
  await page.waitForFunction(() => document.querySelectorAll('.hint-card').length === 3);
  ensure(await page.getByRole('button', { name: /已展开全部三级提示/ }).isDisabled(), 'Hint 3 reaches disabled complete state');
  const after = await history();
  ensure(after.records.length === before.records.length + 1, 'one accepted diagnosis creates one history record');
  ensure(after.activities.length === before.activities.length, 'AI diagnosis does not create a submission');
  ensure(after.records.at(-1)['Hint 使用情况'] === 'Hint 1、2、3', 'Hint usage persists to the original record');
  await page.getByRole('button', { name: '测试结果', exact: true }).click();
  ensure(await page.getByText('当前语言或题目尚未开放执行', { exact: true }).isVisible(), 'unsupported exercise honestly reports execution unavailable');
  ensure(await page.getByRole('button', { name: '运行公开示例', exact: true }).isDisabled(), 'unsupported exercise cannot start execution');
  ensure(await page.locator('.execution-result').count() === 0, 'unsupported exercise has no fabricated output or measured time');
  await page.getByRole('button', { name: '测试用例', exact: true }).click();
  await page.getByRole('button', { name: '记录提交', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '已记录一次本地提交' }).waitFor();
  const submitted = await history();
  ensure(submitted.activities.length === after.activities.length + 1, 'explicit local submission creates exactly one activity');
  await page.getByRole('button', { name: '学习记录', exact: true }).click();
  await page.locator('.history-table-wrap').first().waitFor();
  ensure((await page.locator('main').innerText()).includes('DeepSeek'), 'history displays diagnosis provenance');
  await page.getByRole('button', { name: '工作台', exact: true }).click();
  await page.locator('.monaco-editor').waitFor();
  return { checks, scenario: 'real browser + real Python API + mocked DeepSeek transport', check_count: checks.length };
}
