async (page) => {
  const fixture = await page.request.get('http://127.0.0.1:8000/api/health');
  if (fixture.headers()['x-ai-tutor-test-fixture'] !== 'temporary-data;mock-deepseek') throw new Error('Use tests/browser_server.py: refusing to test against production data');
  const checks = [];
  const ensure = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  const history = async () => (await page.request.get('http://127.0.0.1:8000/api/history')).json();
  const setCode = async (code) => {
    await page.locator('.monaco-editor').click({ position: { x: 120, y: 65 } });
    await page.keyboard.press('Control+A');
    await page.evaluate(text => {
      const data = new DataTransfer(); data.setData('text/plain', text);
      document.activeElement.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }));
    }, code);
    await page.waitForFunction(expected => localStorage.getItem('ai-tutor:draft:v1:198') === expected, code);
  };
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.locator('.monaco-editor').waitFor();
  await setCode('# QA_TIMEOUT\npass\n');
  ensure(await page.locator('.hint-card').count() === 0, 'editing invalidates previous visible hints');
  const beforeFailure = await history();
  await page.getByRole('button', { name: 'AI 诊断', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '超时' }).waitFor();
  const afterFailure = await history();
  ensure(afterFailure.records.length === beforeFailure.records.length, 'timeout creates no successful diagnosis record');
  ensure(await page.evaluate(() => localStorage.getItem('ai-tutor:draft:v1:198') === '# QA_TIMEOUT\npass\n'), 'timeout preserves current draft');
  await setCode('# QA_SLOW\npass\n');
  await page.getByRole('button', { name: 'AI 诊断', exact: true }).click();
  await page.locator('.analysis-loading').waitFor();
  await setCode('# changed while request was pending\npass\n');
  await page.waitForTimeout(1800);
  ensure((await history()).records.length === beforeFailure.records.length, 'editing during slow response prevents history acceptance');
  ensure(await page.locator('.hint-card').count() === 0, 'slow stale response never reappears in AI panel');
  const split = page.getByRole('separator', { name: '调整题目面板宽度' });
  const oldValue = Number(await split.getAttribute('aria-valuenow'));
  await split.focus(); await page.keyboard.press('ArrowRight');
  ensure(Number(await split.getAttribute('aria-valuenow')) > oldValue, 'splitter supports keyboard adjustment');
  const beforeDrag = Number(await split.getAttribute('aria-valuenow'));
  const rect = await split.boundingBox();
  await page.mouse.move(rect.x + rect.width / 2, rect.y + 120); await page.mouse.down();
  await page.mouse.move(rect.x + 60, rect.y + 120, { steps: 5 }); await page.mouse.up();
  ensure(Number(await split.getAttribute('aria-valuenow')) > beforeDrag, 'pointer dragging resizes a panel');
  const widthPreference = await page.evaluate(() => localStorage.getItem('ai-tutor:preferences:layout'));
  await page.reload(); await page.locator('.monaco-editor').waitFor();
  ensure(await page.evaluate(() => localStorage.getItem('ai-tutor:preferences:layout')) === widthPreference, 'panel layout survives refresh');
  await page.getByRole('button', { name: '折叠题目面板', exact: true }).click();
  ensure(await page.getByRole('button', { name: '展开题目面板', exact: true }).isVisible(), 'left panel collapses');
  await page.getByRole('button', { name: '展开题目面板', exact: true }).click();
  await page.getByRole('button', { name: '折叠 AI 面板', exact: true }).click();
  ensure(await page.getByRole('button', { name: '展开 AI 面板', exact: true }).isVisible(), 'right panel collapses');
  await page.getByRole('button', { name: '展开 AI 面板', exact: true }).click();
  await page.getByRole('button', { name: '编辑器全屏', exact: true }).click();
  ensure((await page.locator('.editor-fullscreen').boundingBox()).width > 1500, 'editor fullscreen uses viewport width');
  await page.getByRole('button', { name: '退出编辑器全屏', exact: true }).click();
  await page.getByRole('combobox', { name: '编辑器字号' }).selectOption('18');
  ensure(await page.evaluate(() => getComputedStyle(document.querySelector('.monaco-editor .view-lines')).fontSize === '18px'), 'Monaco font size control changes actual rendering');
  await page.getByRole('button', { name: '恢复默认布局', exact: true }).click();
  await page.setViewportSize({ width: 1024, height: 768 });
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '1024px layout has no page overflow');
  await page.setViewportSize({ width: 390, height: 844 });
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px layout has no page overflow');
  await page.getByRole('navigation', { name: '工作台面板' }).getByRole('button', { name: '题目', exact: true }).click();
  ensure(await page.getByRole('heading', { name: '198. 打家劫舍', exact: true }).isVisible(), 'mobile problem tab opens independently');
  await page.getByRole('navigation', { name: '工作台面板' }).getByRole('button', { name: 'AI 辅导', exact: true }).click();
  ensure(await page.getByRole('button', { name: '获取 AI 提示', exact: true }).isVisible(), 'mobile AI tab opens independently');
  await page.getByRole('navigation', { name: '工作台面板' }).getByRole('button', { name: '代码', exact: true }).click();
  ensure(await page.locator('.monaco-editor').isVisible(), 'mobile editor tab returns to the preserved buffer');
  await page.setViewportSize({ width: 1600, height: 1000 });
  return { checks, check_count: checks.length, real_deepseek_requests: 0 };
}
